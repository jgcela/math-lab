"""Build data/standards.js and data/scope.js from the parsed JSON.

Applies a small list of text corrections where PDF extraction lost glyphs
(stacked fractions, superscripts, math italics). Each corrected objective is
flagged with "corrected": true and keeps the raw extraction in "raw".
"""
import json, sys
std = json.load(open(sys.argv[1], encoding="utf-8"))
scope = json.load(open(sys.argv[2], encoding="utf-8"))

FIXES = {
    "2.I.E.1": "Identify unit and simple fractions (1 whole, ½, ⅓, ¼, ⅔, ¾) using models, pictures, and a number line.",
    "3.I.C.6": "Write and understand the meaning of remainder: 12 ÷ 5 = 2 R 2",
    "6.I.A.4": "Write numbers using scientific notation (1.2 × 10², 4.2 × 10⁻⁶).",
    "7.I.A.1": "Write numbers in scientific notation (1.2 × 10², 4.2 × 10⁻⁶).",
    "ALG1.IV.4": "use slope ratio to investigate the Δy/Δx ratio.",
}
n = 0
for g in std["grades"]:
    for d in g["domains"]:
        for o in d["objectives"] + [o for sd in d["subdomains"] for o in sd["objectives"]]:
            if o["id"] in FIXES:
                o["raw"], o["text"], o["corrected"] = o["text"], FIXES[o["id"]], True
                n += 1
assert n == len(FIXES), n
for row, i in zip(scope, range(len(scope))):
    row["id"] = f"SS-{row['strand']}-{i+1}"

hdr = "/* Generated by tools/build_data.py from the Archdiocese of Denver 2018 Math Standards PDF. Do not edit by hand. */\n"
open("data/standards.js", "w", encoding="utf-8").write(hdr + "window.CM = window.CM || {};\nCM.STANDARDS = " + json.dumps(std, ensure_ascii=False) + ";\n")
open("data/scope.js", "w", encoding="utf-8").write(hdr + "window.CM = window.CM || {};\nCM.SCOPE = " + json.dumps(scope, ensure_ascii=False) + ";\n")
print("ok", n, "corrections;", len(scope), "scope rows")
